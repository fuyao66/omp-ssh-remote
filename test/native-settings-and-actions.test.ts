test("forwarded execution settings keep their native type, default and unit", () => {
  for (const [key, expected] of Object.entries(NATIVE_SETTING_DEFINITIONS) as [ForwardedSettingKey, typeof NATIVE_SETTING_DEFINITIONS[ForwardedSettingKey]][]) {
    const setting = lookup(key) as { type: string; default: unknown; enumValues?: readonly string[]; ui?: { label?: string; description?: string } } | undefined;
    expect(setting, key).toBeDefined();
    const isRuleList = FORWARDED_EXECUTION_SETTINGS[key].type === "interceptor-rules";
    expect({
      type: setting!.type,
      default: isRuleList ? "(native rules)" : setting!.default,
      label: setting!.ui?.label ?? "(none)",
      ...(setting!.enumValues ? { enumValues: [...setting!.enumValues] } : {}),
    }, key).toEqual(expected);
    // The companion must accept the native default; otherwise capture silently drops a configured value.
    expect(isValidForwardedSetting(key, setting!.default), key).toBe(true);
  }
  // Seconds versus milliseconds is carried by the description where the label does not say it.
  expect((lookup("tools.maxTimeout") as { ui: { description: string } }).ui.description).toContain("in seconds");
  expect((lookup("lsp.requestTimeout") as { ui: { description: string } }).ui.description).toStartWith("Seconds ");
  expect(Object.keys(NATIVE_SETTING_DEFINITIONS).sort()).toEqual(Object.keys(FORWARDED_EXECUTION_SETTINGS).sort());
});

/**
 * Native readers of forwarded handles that never run in the remote worker: host UI,
 * host session plumbing, and tools the plugin leaves local. The registry module
 * names a handle only in its documentation.
 */
const HOST_SIDE_SETTING_READERS = [
  "config/registry.ts", "disasm/prelude-definition.ts", "main.ts", "modes/controllers/input-controller.ts",
  "modes/interactive-mode.ts", "sdk.ts", "session/agent-session.ts", "session/bash-runner.ts",
  "tools/browser.ts", "tools/computer.ts", "tools/fetch.ts", "tools/gh.ts",
];

test("every native reader of a forwarded setting is classified", async () => {
  const root = dirname(Bun.resolveSync("@oh-my-pi/pi-coding-agent/sdk", import.meta.dir));
  const sources = new Map<string, string>();
  for (const file of await readdir(root, { recursive: true })) {
    if (file.endsWith(".ts")) sources.set(file, await readFile(join(root, file), "utf8"));
  }
  const handles = new Map<string, string>();
  for (const [file, text] of sources) {
    for (const [, handle, key] of text.matchAll(/export const (\w+) = register(?:<[^>]*>)?\(\{\s*id: "([^"]+)"/g)) {
      if (key! in FORWARDED_EXECUTION_SETTINGS) handles.set(handle!, file);
    }
  }
  // A key defined another way would escape this scan; fail rather than under-report.
  expect(handles.size).toBe(Object.keys(FORWARDED_EXECUTION_SETTINGS).length);
  const readers = new Set<string>();
  for (const [handle, definition] of handles) {
    const pattern = new RegExp(`\\b${handle}\\b`);
    for (const [file, text] of sources) if (file !== definition && pattern.test(text)) readers.add(file);
  }
  // New readers: classify by whether the remote worker runs them, and re-read their unit handling.
  const contract = SEMANTIC_SDK_CONTRACTS.find(entry => entry.id === "execution-settings-consumer-units")!;
  const unclassified = [...readers].filter(file => !contract.native.includes(file) && !HOST_SIDE_SETTING_READERS.includes(file));
  expect(unclassified).toEqual([]);
  // Stale entries would make the review trigger fire on files that no longer read these settings.
  expect([...SETTING_CONSUMERS, ...HOST_SIDE_SETTING_READERS].filter(file => !readers.has(file))).toEqual([]);
});
