/**
 * Native LSP actions that only query. Any other action holds deferred diagnostics
 * as a possible workspace mutation. A new native action fails here until it is
 * classified by reading what it does in lsp/tool.ts.
 */
const READ_ONLY_LSP_ACTIONS = [
  "capabilities", "definition", "diagnostics", "hover", "implementation", "references", "reload", "status", "symbols", "type_definition",
];

test("every native LSP action is classified as mutating or read-only", () => {
  const actions = (lspSchema.toJsonSchema() as { properties: { action: { enum: string[] } } }).properties.action.enum;
  const mutating = actions.filter(action => mayMutateLsp("lsp", { action }));
  expect(mutating.sort()).toEqual(["code_actions", "rename", "rename_file", "request"]);
  expect(actions.filter(action => !mutating.includes(action)).sort()).toEqual(READ_ONLY_LSP_ACTIONS);
});

